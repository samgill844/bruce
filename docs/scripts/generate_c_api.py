"""Generate the bruce_c reference and verify positional argument order against C."""
from pathlib import Path
import re
from generate_api import ARGS, INFO, ROOT

# All positional arguments are required by the current NumPy-C wrappers.
LC = 't t_zero period radius_1 k incl e w c alpha cadence noversample light_3 ld_law accurate_tp'
SPECS = {
 'loglike': ('y yerr model jitter offset', 'Negative Gaussian log likelihood summed over observations.'),
 'lc': (LC, 'Transit flux array.'),
 'lc_loglike': ('t flux flux_err '+LC.split(' ',1)[1]+' jitter offset', 'Scalar negative transit log likelihood.'),
 'rv1': ('t t_zero period K1 e w incl V0 accurate_tp', 'Primary velocity array.'),
 'rv1_loglike': ('t rv rv_err t_zero period K1 e w incl V0 accurate_tp offset jitter', 'Scalar negative primary-RV log likelihood.'),
 'rv2': ('t t_zero period K1 K2 e w incl V0 accurate_tp', 'Tuple (primary_velocity, secondary_velocity).'),
 'rv2_loglike': ('t rv1 rv2 rv1_err rv2_err t_zero period K1 K2 e w incl V0 accurate_tp offset jitter', 'Scalar sum of negative log likelihoods for both RV datasets.'),
 'xyzz': ('t t_zero period incl e w accurate_tp', 'Dictionary of arrays x, y, z, zz and f. x/y/z are coordinates in semi-major-axis units; zz=10*sqrt(x*x+y*y). f=sin(nu+w)*sin(incl) is the front/back indicator.'),
 'bin_data': ('time flux bin_size', INFO['bin_data'][1]),
 'bin_data_adaptive': ('time flux gap target_bin_size min_acceptable_bin_size', INFO['bin_data_adaptive'][1]),
 'median_filter': ('time flux window', 'Time-window median trend array. The current implementation caps a window at 1024 samples and can include boundary-neighbour samples.'),
 'convolve_1d': ('time flux window', 'Time-window arithmetic-mean trend array.'),
 'check_proximity_of_timestamps': ('time_trial time width', 'Boolean array marking trial epochs within width/2 of observed timestamps.'),
 'template_match_reduce': ('time_trial time flux flux_err normalisation_model width period radius_1 k incl e w c alpha cadence noversample light_3 ld_law accurate_tp jitter offset', 'One-dimensional score array, 2*(logL_transit-logL_baseline), per trial epoch.'),
 'template_match_batch_reduce': ('time_trial time flux flux_err normalisation_model period radius_1 k incl e w c alpha cadence noversample light_3 ld_law accurate_tp jitter offset', 'Score array with shape (n_epochs, n_radius_1, n_k, n_incl); geometry parameters are arrays.'),
 'phase_dispersion': ('time_trial peaks periods time flux flux_err', 'Tuple (dispersion, L), one value per trial period. dispersion sums pairwise wrapped phase distances between selected epochs. L is currently zero: its photometric statistic is not implemented.'),
}
ALIASES = {'time_array':'t','time_obj':'time','a_g_obj':'t','x_obj':'time',
           'y_obj':'flux','time_trial_obj':'time_trial'}
ARRAYS = {'t','time','flux','flux_err','normalisation_model','rv','rv_err','rv1','rv2',
          'rv1_err','rv2_err','y','yerr','model','time_trial','peaks','periods'}
INTS = {'noversample','ld_law','accurate_tp','offset'}


def main():
    source = (ROOT/'src/bruce_c/bruce_numpy.c').read_text()
    # Strip comments before checking PyArg_ParseTuple variables.
    source = re.sub(r'/\*.*?\*/|//[^\n]*', '', source, flags=re.S)
    exports = set(re.findall(r'\{"(\w+)",\s*\w+,\s*METH_VARARGS',source))
    assert exports == set(SPECS), (exports-set(SPECS), set(SPECS)-exports)
    text = ['bruce_c: low-level numerical API', '='*len('bruce_c: low-level numerical API'), '',
            '.. This file is generated by docs/scripts/generate_c_api.py.', '',
            '``bruce_c`` is the compiled NumPy-C extension underlying the Python',
            'interface. It exposes selected modelling, likelihood, orbit, filtering',
            'and search routines directly. Import it with ``import bruce_c``.', '',
            'All signatures below are **positional-only** and every argument is',
            'required; the extension supplies no Python-wrapper defaults. Units and',
            'model conventions follow :doc:`../conventions`. Parameter order can differ',
            'from the higher-level functions, especially the RV likelihoods.', '',
            'Use one-dimensional, contiguous NumPy arrays with matching lengths for',
            'observations, uncertainties and models; float64 is the numerical type.',
            'The wrappers convert many array inputs, but validation varies by entry',
            'point. Supply finite data and positive errors explicitly. ``peaks`` uses',
            'integer indices (NumPy intc). Geometry is scalar except in the batch',
            'template routine, where radius_1, k and incl are arrays.', '',
            'The C likelihood functions, including ``bruce_c.loglike``, return',
            '**negative** log likelihood and omit the additive Gaussian constant.',
            '``offset=1`` includes the variance-dependent logarithmic term.',
            'Template scores instead report twice the log-likelihood improvement.', '',
            '`C wrapper source <https://github.com/samgill844/bruce/blob/main/src/bruce_c/bruce_numpy.c>`__', '']
    for name, (params, returns) in SPECS.items():
        body = re.search(r'static PyObject\s*\*\s*'+name+r'\([^\n]*\)\s*\{(.*?)(?=\nstatic |\nstatic struct)',source,re.S).group(1)
        parse = re.search(r'PyArg_ParseTuple\((.*?)\)\)',body,re.S).group(1)
        c_names = re.findall(r'&(\w+)',parse)
        c_names = [n for n in c_names if n!='PyArray_Type']
        actual = [ALIASES.get(n, re.sub(r'_(array|obj)$','',n)) for n in c_names]
        # The loglike y array and lc/xyzz time array have different public labels.
        if name == 'loglike': actual = c_names
        if name in ('bin_data','bin_data_adaptive'): actual[0]='time'
        assert actual == params.split(), (name,actual,params)
        text += [name, '-'*len(name), '', f'.. py:function:: bruce_c.{name}({", ".join(params.split())}, /)', '',
                 '   '+returns, '']
        for arg in params.split():
            desc = ARGS.get(arg)
            if arg == 'window': desc = 'Full time-window width in the same units as time.'
            if arg == 'peaks': desc = 'Integer indices into time_trial selecting event epochs; must be within array bounds.'
            if arg == 'periods': desc = 'One-dimensional array of positive trial periods, in the same units as time_trial.'
            if arg == 'width' and name=='template_match_reduce': desc = 'Full time width of the observation window around each trial epoch.'
            if arg == 'y': desc = 'Observed values on the model grid.'
            if arg == 'flux' and name=='lc_loglike': desc = 'Observed relative flux, required for this likelihood entry point.'
            if arg in ('rv','rv1','rv2') and name.endswith('_loglike'): desc = 'Observed velocities for the corresponding component; required, not None.'
            assert desc is not None, (name,arg)
            typ = 'ndarray' if arg in ARRAYS or (name=='template_match_batch_reduce' and arg in ('radius_1','k','incl')) else 'int' if arg in INTS else 'float'
            if name=='loglike' and arg=='offset': typ='float';desc='Numeric flag, 1 includes the logarithmic variance term; 0 omits it (this legacy entry point parses a double).'
            text += [f'   :param {arg}: {desc}', f'   :type {arg}: {typ}']
        text += ['   :returns: '+returns, '']
    (ROOT/'docs/api/bruce_c.rst').write_text('\n'.join(text)+'\n')

if __name__ == '__main__':
    main()
